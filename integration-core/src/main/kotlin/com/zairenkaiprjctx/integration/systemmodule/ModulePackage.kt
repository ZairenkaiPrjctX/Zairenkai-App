@Serializable
data class ManagerRequirement(
    @SerialName("min_version_code") val minVersionCode: Long? = null,
    val evidence: String,
)

@Serializable
data class ModuleConflict(val id: String, val reason: String)

@Serializable
data class ModuleRequirements(
    val arch: String,
    val abi: String,
    @SerialName("min_api") val minApi: Int,
    /** Keys: magisk, kernelsu, apatch. A manager not listed here is not supported. */
    val managers: Map<String, ManagerRequirement>,
    @SerialName("required_paths") val requiredPaths: List<String> = emptyList(),
    @SerialName("depends_on") val dependsOn: List<String> = emptyList(),
    val conflicts: List<ModuleConflict> = emptyList(),
)

@Serializable
data class ModuleSource(val repository: String, val commit: String)

/** Where the module goes and how it starts, stops and is removed, from its own scripts. */
@Serializable
data class ModuleLifecycle(
    val destinations: Map<String, String> = emptyMap(),
    val startup: String = "",
    val shutdown: String = "",
    val uninstall: String = "",
    val recovery: String = "",
    val kernel: String = "",
)

/**
 * One module packaged in this APK (`assets/system-modules.json`, generated by
 * build-components.sh from integration/system-modules.json and the built zip).
 */
@Serializable
data class BundledModule(
    val id: String,
    /** "base" or "optional". */
    val role: String,
    val name: String,
    /** Registry capability ids this module provides when its runtime answers. */
    val features: List<String>,
    val requirements: ModuleRequirements,
    @SerialName("reboot_required") val rebootRequired: Boolean,
    @SerialName("data_dir") val dataDir: String,
    @SerialName("runtime_check") val runtimeCheck: String,
    /** Devices with a recorded install test. Empty means the module is experimental everywhere. */
    @SerialName("validated_on") val validatedOn: List<String> = emptyList(),
    val risks: List<String> = emptyList(),
    val lifecycle: ModuleLifecycle = ModuleLifecycle(),
    val file: String,
    val version: String,
    @SerialName("version_code") val versionCode: Long,
    val size: Long,
    val sha256: String,
    val source: ModuleSource,
    /** Every zip entry and its SHA-256, recorded at build time. */
    val entries: Map<String, String>,
    /** Entries the build matched byte for byte to the module/ sources at [source]. */
    @SerialName("source_matched") val sourceMatched: List<String>,
)

@Serializable
data class ModuleCatalog(val schema: Int, val modules: List<BundledModule>) {
    fun byId(id: String): BundledModule? = modules.firstOrNull { it.id == id }
    val base: BundledModule? get() = modules.firstOrNull { it.role == "base" }

    companion object {
        private val json = Json { ignoreUnknownKeys = true }
        private val SHA = Regex("^[0-9a-f]{64}$")

        fun parse(text: String): ModuleCatalog {
            val c = json.decodeFromString<ModuleCatalog>(text)
            require(c.schema == 1) { "unsupported module catalog schema ${c.schema}" }
            require(c.modules.map { it.id }.toSet().size == c.modules.size) { "duplicate module ids" }
            for (m in c.modules) {
                require(ModuleIds.isValid(m.id)) { "invalid module id ${m.id}" }
                require(m.file == "system-modules/${m.id}.zip") { "unexpected file ${m.file} for ${m.id}" }
                require(SHA.matches(m.sha256) && m.entries.values.all(SHA::matches)) { "malformed digest for ${m.id}" }
                require(m.source.commit.matches(Regex("^[0-9a-f]{40}$"))) { "source commit of ${m.id} is not a full SHA" }
                require(m.sourceMatched.all { it in m.entries }) { "matched entries of ${m.id} are not in the zip" }
            }
            return c
        }
    }
}

/** Why a package was rejected. Each value maps to one check in [ModulePackageVerifier]. */
enum class PackageFault {
    UNREADABLE,
    SIZE_MISMATCH,
    DIGEST_MISMATCH,
    NOT_A_ZIP,
    UNSAFE_ENTRY,
    UNEXPECTED_ENTRIES,
    ENTRY_DIGEST_MISMATCH,
    MODULE_ID_MISMATCH,
    VERSION_MISMATCH,
    INSTALLER_MISSING,
}

sealed interface PackageVerdict {
    data class Verified(val module: BundledModule, val file: File, val checks: List<String>) : PackageVerdict
    data class Rejected(val fault: PackageFault, val detail: String) : PackageVerdict
}

/**
 * Verifies a module zip against its catalog record before any root command sees it:
 * size, whole-file SHA-256, a zip whose entry set is exactly the recorded one (no absolute or
 * `..` paths), every entry's SHA-256, module.prop id, version and versionCode, and the
 * installer entries the build matched to the reviewed source.
 *
 * Trust: the catalog and the zip both come from this APK, so the APK signature is what makes
 * them an authorised release. The digests then guard the copy the root manager reads.
 */
object ModulePackageVerifier {
    private val INSTALLER = listOf("customize.sh", "META-INF/com/google/android/update-binary")

    fun sha256(input: InputStream): String {
        val md = MessageDigest.getInstance("SHA-256")
        val buf = ByteArray(64 * 1024)
        while (true) {
            val n = input.read(buf)
            if (n < 0) break
            md.update(buf, 0, n)
        }
        return md.digest().joinToString("") { "%02x".format(it) }
    }

    fun verify(file: File, module: BundledModule): PackageVerdict {
        val checks = mutableListOf<String>()
        if (!file.isFile) return PackageVerdict.Rejected(PackageFault.UNREADABLE, "${file.name} does not exist")
        if (file.length() != module.size) {
            return PackageVerdict.Rejected(PackageFault.SIZE_MISMATCH, "size ${file.length()} bytes, expected ${module.size}")
        }
        checks += "size ${module.size} bytes"
        val digest = try {
            file.inputStream().use(::sha256)
        } catch (e: Exception) {
            return PackageVerdict.Rejected(PackageFault.UNREADABLE, e.message ?: "read failed")
        }
        if (digest != module.sha256) return PackageVerdict.Rejected(PackageFault.DIGEST_MISMATCH, "SHA-256 $digest, expected ${module.sha256}")
        checks += "SHA-256 ${module.sha256}"
        val zip = try {
            ZipFile(file)
        } catch (e: Exception) {
            return PackageVerdict.Rejected(PackageFault.NOT_A_ZIP, e.message ?: "not a zip")
        }
        zip.use { z ->
            val entries = z.entries().toList()
            val names = entries.map { it.name }
            names.firstOrNull { it.startsWith("/") || it.contains('\\') || it.split('/').any { p -> p == ".." } || it.endsWith("/") }?.let {
                return PackageVerdict.Rejected(PackageFault.UNSAFE_ENTRY, "entry $it")
            }
            if (names.size != names.toSet().size || names.toSet() != module.entries.keys) {
                val extra = names.toSet() - module.entries.keys
                val missing = module.entries.keys - names.toSet()
                return PackageVerdict.Rejected(PackageFault.UNEXPECTED_ENTRIES, "unexpected $extra, missing $missing")
            }
            for (e in entries) {
                val d = z.getInputStream(e).use(::sha256)
                if (d != module.entries[e.name]) return PackageVerdict.Rejected(PackageFault.ENTRY_DIGEST_MISMATCH, e.name)
            }
            checks += "${names.size} entries match the build record"
            val prop = ModuleProp.parse(z.getInputStream(z.getEntry("module.prop") ?: return PackageVerdict.Rejected(PackageFault.MODULE_ID_MISMATCH, "no module.prop")).use { it.readBytes().decodeToString() })
            if (prop["id"] != module.id) return PackageVerdict.Rejected(PackageFault.MODULE_ID_MISMATCH, "module.prop id ${prop["id"]}, expected ${module.id}")
            if (prop["version"] != module.version || prop["versionCode"]?.toLongOrNull() != module.versionCode) {
                return PackageVerdict.Rejected(PackageFault.VERSION_MISMATCH, "module.prop ${prop["version"]} (${prop["versionCode"]}), expected ${module.version} (${module.versionCode})")
            }
            checks += "module.prop: ${module.id} ${module.version} (${module.versionCode})"
            val unmatched = INSTALLER.filterNot { it in module.sourceMatched }
            if (unmatched.isNotEmpty()) return PackageVerdict.Rejected(PackageFault.INSTALLER_MISSING, "not matched to source: $unmatched")
            checks += "installer scripts identical to ${module.source.repository} @ ${module.source.commit.take(12)} (${module.sourceMatched.size} files)"
        }
        return PackageVerdict.Verified(module, file, checks)
    }
}
