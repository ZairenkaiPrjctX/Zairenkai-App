// Integration metadata (inventory, lock) is copied into the APK's assets so the app can show
// every repository's disposition and the revisions it was built from, together with the app's
// own licence and notice.
val integrationMeta = layout.buildDirectory.dir("generated/integration-meta")
val copyIntegrationMeta = tasks.register<Copy>("copyIntegrationMeta") {
    from(
        files(
            rootProject.file("integration/organization-repositories.json"),
            rootProject.file("integration/repository-lock.json"),
            // Module-signing public keys: the app trusts only these to authenticate module releases.
            rootProject.file("integration/module-trust.json"),
        ),
    ) { into("integration") }
    from(files(rootProject.file("LICENSE"), rootProject.file("NOTICE"))) { into("licenses/zairenkai-app") }
    into(integrationMeta)
}

// Notices for the Android libraries in the release runtime classpath: coordinates, the licence
// each POM declares (or its parent's), and the source URL. The release check fails on a library
// with no declared licence.
val androidNotices = layout.buildDirectory.dir("generated/notices")
val generateAndroidNotices = tasks.register("generateAndroidNotices") {
    val out = androidNotices.map { it.file("licenses/android/NOTICES.txt") }
    outputs.file(out)
    outputs.upToDateWhen { false }
    doLast {
        val ids = configurations.getByName("releaseRuntimeClasspath").incoming.resolutionResult.allComponents
            .mapNotNull { it.id as? org.gradle.api.artifacts.component.ModuleComponentIdentifier }
            .sortedBy { it.displayName }
        val factory = javax.xml.parsers.DocumentBuilderFactory.newInstance().apply { isNamespaceAware = false }
        fun pom(group: String, module: String, version: String): org.w3c.dom.Document? {
            val r = dependencies.createArtifactResolutionQuery().forModule(group, module, version)
                .withArtifacts(org.gradle.maven.MavenModule::class.java, org.gradle.maven.MavenPomArtifact::class.java).execute()
            val file = r.resolvedComponents.flatMap { it.getArtifacts(org.gradle.maven.MavenPomArtifact::class.java) }
                .filterIsInstance<org.gradle.api.artifacts.result.ResolvedArtifactResult>().firstOrNull()?.file ?: return null
            return factory.newDocumentBuilder().parse(file)
        }
        fun org.w3c.dom.Element.child(name: String): org.w3c.dom.Element? =
            (0 until childNodes.length).map { childNodes.item(it) }.filterIsInstance<org.w3c.dom.Element>().firstOrNull { it.tagName == name }
        fun licences(group: String, module: String, version: String, depth: Int = 0): List<String> {
            val doc = pom(group, module, version) ?: return emptyList()
            val root = doc.documentElement
            val ls = root.child("licenses")?.let { l ->
                (0 until l.childNodes.length).map { l.childNodes.item(it) }.filterIsInstance<org.w3c.dom.Element>()
                    .map { listOfNotNull(it.child("name")?.textContent?.trim(), it.child("url")?.textContent?.trim()).joinToString(" — ") }
            }.orEmpty()
            if (ls.isNotEmpty() || depth > 4) return ls
            val parent = root.child("parent") ?: return emptyList()
            return licences(parent.child("groupId")!!.textContent.trim(), parent.child("artifactId")!!.textContent.trim(), parent.child("version")!!.textContent.trim(), depth + 1)
        }
        val missing = mutableListOf<String>()
        val text = StringBuilder()
        text.appendLine("Android libraries in Zairenkai App (release runtime classpath)")
        text.appendLine("Generated by the generateAndroidNotices Gradle task from each library's POM.")
        text.appendLine()
        for (c in ids) {
            val ls = licences(c.group, c.module, c.version)
            if (ls.isEmpty()) missing += c.displayName
            text.appendLine("${c.group}:${c.module}:${c.version}")
            ls.forEach { text.appendLine("  Licence: $it") }
            if (ls.isEmpty()) text.appendLine("  Licence: NOT DECLARED")
        }
        text.appendLine()
        text.appendLine("Apache License 2.0 text: licenses/zairenkai-app/LICENSE in this APK, or https://www.apache.org/licenses/LICENSE-2.0.txt")
        val f = out.get().asFile
        f.parentFile.mkdirs()
        f.writeText(text.toString())
        if (missing.isNotEmpty()) throw GradleException("Android libraries without a declared licence: $missing")
        logger.lifecycle("generateAndroidNotices: ${ids.size} libraries -> $f")
    }
}

// Components built by integration/scripts/build-components.sh at the locked commits.
val componentsDir = rootProject.file("integration/out")
val allowMissingComponents = providers.gradleProperty("zairenkai.allowMissingComponents").map { it.toBoolean() }.orElse(false)
val verifyIntegrationComponents = tasks.register("verifyIntegrationComponents") {
    val required = listOf("arm64-v8a", "armeabi-v7a", "x86_64").flatMap { listOf("jniLibs/$it/libzart.so", "jniLibs/$it/libzthermal.so") } +
        listOf(
            "assets/afid/device-candidates.json", "assets/components.json",
            "assets/licenses/zthermal/LICENSE", "assets/licenses/zthermal/NOTICE",
            "assets/licenses/zart/LICENSE", "assets/licenses/zart/NOTICE",
            // The single root module (Zairenkai-Modules): zcored and zfasd.
            "assets/system-modules.json", "assets/system-modules/zairenkai.zip",
        )
    val allow = allowMissingComponents
    doLast {
        val missing = required.filterNot { componentsDir.resolve(it).isFile }
        if (missing.isNotEmpty()) {
            val msg = "Integration components missing: $missing. Run integration/scripts/build-components.sh, " +
                "or pass -Pzairenkai.allowMissingComponents=true to build an APK whose ART, thermal-sensor, " +
                "system-module and device-database features report NATIVE_COMPONENT_UNAVAILABLE / INITIALIZATION_FAILED."
            if (allow.get()) logger.warn("WARNING: $msg") else throw GradleException(msg)
        }
    }
}

android {
    namespace = "com.zairenkaiprjctx.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.zairenkaiprjctx.app"
        minSdk = 29
        targetSdk = 35
        versionCode = 1
        versionName = "0.1.0"
        ndk {
            // The ABIs zart and zthermal are built for (integration/repository-lock.json).
            abiFilters += listOf("arm64-v8a", "armeabi-v7a", "x86_64")
        }
    }

    // Release signing only when the release keystore is provided by the environment (the release
    // workflow's protected secrets). Nothing about the key is in the repository; without it,
    // assembleRelease produces an unsigned engineering APK.
    val releaseKeystore = System.getenv("ZAIRENKAI_RELEASE_KEYSTORE_FILE")?.let(::file)?.takeIf { it.isFile }
    if (releaseKeystore != null) {
        signingConfigs.create("release") {
            storeFile = releaseKeystore
            storePassword = System.getenv("ZAIRENKAI_RELEASE_KEYSTORE_PASSWORD")
            keyAlias = System.getenv("ZAIRENKAI_RELEASE_KEY_ALIAS")
            keyPassword = System.getenv("ZAIRENKAI_RELEASE_KEY_PASSWORD")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            if (releaseKeystore != null) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    packaging {
        jniLibs {
            // zart and zthermal are executables, not JNI libraries: it must be extracted to nativeLibraryDir
            // so it can be executed (app data directories are not executable for targetSdk >= 29).
            useLegacyPackaging = true
        }
    }

    sourceSets["main"].apply {
        jniLibs.srcDir(componentsDir.resolve("jniLibs"))
        assets.srcDirs(componentsDir.resolve("assets"), integrationMeta, androidNotices)
    }

    androidResources {
        // Declares English and Indonesian for the per-app language setting (Android 13+).
        generateLocaleConfig = true
        // Only the app's own languages: otherwise library strings in ~80 other languages would
        // mix with English app text on, for example, a German device.
        localeFilters += listOf("en", "in")
    }

    bundle {
        // The language is chosen in the app (AppLanguage), not by the system language, so an App
        // Bundle install must carry both languages instead of only the device's.
        language { enableSplit = false }
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
            all {
                // Robolectric downloads its android-all jars itself; Maven Central rate-limits this
                // build environment, so allow overriding the repository from the environment.
                System.getenv("ROBOLECTRIC_REPO_URL")?.let { url -> it.systemProperty("robolectric.dependency.repo.url", url) }
                // Screenshot gallery (app/src/test/.../ScreenshotGallery.kt): skipped unless set.
                System.getenv("ZAIRENKAI_SCREENSHOT_DIR")?.let { dir -> it.systemProperty("zairenkai.screenshotDir", dir) }
            }
        }
    }

    lint {
        abortOnError = true
        checkDependencies = true
    }
}

