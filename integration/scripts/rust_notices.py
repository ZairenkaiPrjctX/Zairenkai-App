#!/usr/bin/env python3
"""Write the third-party notices for one Rust binary built from a checked-out workspace.

Usage: rust_notices.py --workspace <dir> --package <name> --target <triple> --component <label>
                       --out <THIRD_PARTY_NOTICES.txt>

Walks `cargo metadata --locked` from <package> through normal and build dependencies (not dev)
for <target>, and writes, for every crate outside the workspace: name, version, licence
expression, repository, and the full text of each licence or notice file the crate ships
(LICENSE*, LICENCE*, COPYING*, NOTICE*, UNLICENSE). Fails if a crate declares no licence, or
ships no licence text, so a notice can never silently disappear.
"""
import argparse
import json
import pathlib
import subprocess
import sys

NOTICE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense")


def main() -> None:
    ap = argparse.ArgumentParser()
    for a in ("workspace", "package", "target", "component", "out"):
        ap.add_argument(f"--{a}", required=True)
    a = ap.parse_args()
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", a.target],
        cwd=a.workspace, check=True, capture_output=True, text=True,
    ).stdout)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    roots = [pid for pid in members if packages[pid]["name"] == a.package]
    if len(roots) != 1:
        sys.exit(f"rust_notices: package {a.package} not found in {a.workspace}")

    seen, todo = set(), list(roots)
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for d in nodes[pid]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                todo.append(d["pkg"])

    crates = sorted((packages[p] for p in seen if p not in members), key=lambda p: (p["name"], p["version"]))
    out = [
        f"Third-party software in {a.component}",
        f"({a.package}, {a.target}; generated by integration/scripts/rust_notices.py from Cargo.lock)",
        "",
        f"{len(crates)} crates are compiled into this binary. Each is listed with its licence and the",
        "licence and notice texts it ships.",
        "",
    ]
    problems = []
    for p in crates:
        root = pathlib.Path(p["manifest_path"]).parent
        files = sorted(f for f in root.iterdir() if f.is_file() and f.name.lower().startswith(NOTICE_PREFIXES))
        if p.get("license_file"):
            lf = root / p["license_file"]
            if lf.is_file() and lf not in files:
                files.append(lf)
        if not p.get("license") and not p.get("license_file"):
            problems.append(f"{p['name']} {p['version']}: no licence declared")
        if not files:
            problems.append(f"{p['name']} {p['version']}: ships no licence text")
        out += ["=" * 78, f"{p['name']} {p['version']}", f"Licence: {p.get('license') or p.get('license_file')}"]
        if p.get("repository"):
            out.append(f"Source: {p['repository']}")
        for f in files:
            out += ["", f"--- {f.name} ---", f.read_text(errors="replace").rstrip()]
        out.append("")
    if problems:
        sys.exit("rust_notices: " + "; ".join(problems))
    path = pathlib.Path(a.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n")
    print(f"rust_notices: {a.component}: {len(crates)} crates -> {path}")


if __name__ == "__main__":
    main()
